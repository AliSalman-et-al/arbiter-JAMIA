test_that('strictness, severity and descriptive mechanism counts are reproduced', {
  cells <- adjudication_cells(inputs)
  d <- vindicated_disagreements(cells) |> distinct(source,direction,all_n)
  expect_equal(d$all_n[d$source=='ARBITER' & d$direction=='More severe'],88L)
  expect_equal(sum(d$all_n[d$source=='ARBITER']),124L)
  expect_equal(d$all_n[d$source=='Unassisted' & d$direction=='More severe'],69L)
  expect_equal(sum(d$all_n[d$source=='Unassisted']),115L)
  old <- getwd(); setwd(analysis_dir); on.exit(setwd(old))
  mechanism <- question51_mechanism(inputs,localise_errors(inputs,cells))
  expect_equal(nrow(mechanism),18L)
  expect_equal(sum(mechanism$registry_or_protocol_or_sap),13L)
  expect_false(any(mechanism$mentions_document))
  expect_equal(table(mechanism$answer)[c('PY','Y')] |> as.integer(),c(16L,2L))
  expect_true(all(mechanism$reference_A==mechanism$reference_Z))
  severity <- manuscript_data('severity-win-share')
  expect_equal(severity$count,c(44L,1L,0L,10L,6L,1L))
  changed <- manuscript_data('rules-only-recomputation-changed') |> filter(consensus,discordant)
  expect_equal(nrow(changed),3L)
  expect_true(all(changed$recomputed==changed$preferred))
})
