test_that('paired differences use both ratings on the same 154 disputed cells', {
  cells <- adjudication_cells(inputs)
  w <- stratified_cluster_weights(inputs$trials,10000,20261018)
  d <- independent_paired_difference(cells,w)
  expect_equal(d$n,c(154L,154L))
  expect_equal(d$ARBITER_count,c(107L,120L))
  expect_equal(d$Unassisted_count,c(69L,76L))
  expect_equal(d$estimate,c(38,44)/154)
  # A paired sample with one trial and opposite outcomes always has difference one.
  z <- tibble(slug='x',kit='High',nokit='Low',own_A='High',own_Z='High')
  toy <- independent_paired_difference(z,matrix(1L,1,10,dimnames=list('x',NULL)))
  expect_equal(toy$estimate,c(1,1)); expect_equal(toy$lower,c(1,1)); expect_equal(toy$upper,c(1,1))
})
