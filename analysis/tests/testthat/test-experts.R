test_that('independent comparisons retain separate experts and domain populations', {
  x <- expert_agreement(inputs,stratified_cluster_weights(inputs$trials,100,7))
  expect_setequal(x$estimates$adjudicator,c('1','2'))
  expect_setequal(x$estimates$domain,c('D1-D5',paste0('D',1:5),'Overall'))
  expect_true(all(x$estimates$n[x$estimates$domain=='D1-D5']==510L))
  expect_true(all(x$estimates$n[x$estimates$domain!='D1-D5']==102L))
  expect_true(all(x$differences$comparison=='ARBITER minus Unassisted'))
  pooled <- filter(x$estimates,domain=='D1-D5',metric=='accuracy')
  expect_equal(pooled$count,c(371L,332L,301L,433L,400L,362L))
  overall <- filter(x$estimates,domain=='Overall',metric=='accuracy')
  expect_equal(overall$count,c(39L,27L,72L,57L))
  expect_setequal(overall$source,c('ARBITER','Unassisted'))
  expect_true(all(overall$population=='All trials'))
})

test_that('signalling diagnostics retain both codings and paired intersections', {
  comparisons <- match_signalling(parse_signalling_evidence(inputs$evidence),inputs$signals)
  x <- signalling_agreement(comparisons,stratified_cluster_weights(inputs$trials,100,7))
  expect_setequal(x$estimates$group,c('Overall',paste0('D',1:5)))
  expect_setequal(x$estimates$level,c('five','collapsed'))
  paired <- filter(x$differences,adjudicator=='1',group=='D3')
  expect_equal(paired$n,c(165L,165L))
  expect_lt(paired$estimate[paired$level=='five'],0)
  expect_gt(paired$estimate[paired$level=='collapsed'],0)
  expect_true(all(inputs$evidence$phase=='Independent'))
  expect_setequal(unique(x$differences$group),c('Overall',paste0('D',1:5),question_map()$question))
  q <- filter(x$differences,group=='4.1')
  expect_equal(round(100*q$estimate[q$level=='five'],1),c(-39.6,-28.4))
  expect_equal(q$estimate[q$level=='collapsed'],c(0,0))
  expect_equal(nrow(x$differences),112L)
})

test_that('rules-only diagnostic changes contradictions but not invalid or missing paths', {
  checks <- domain_checks(inputs)
  weights <- stratified_cluster_weights(inputs$trials,100,7)
  x <- rules_only_diagnostic(inputs,checks,adjudication_cells(inputs),weights)
  expect_equal(nrow(x$changed),26L)
  expect_equal(filter(x$agreement,metric=='accuracy')$count,c(324L,391L))
  expect_equal(filter(x$agreement,metric=='accuracy')$n,c(510L,510L))
  expect_true(all(x$agreement$source=='Unassisted' & x$agreement$domain=='D1-D5'))
  invalid <- checks |> filter(arm=='Baseline-Sonnet',status=='Invalid answer path') |> select(slug,domain)
  expect_equal(nrow(inner_join(x$changed,invalid,by=c('slug','domain'))),0L)
  expect_equal(sum(is.na(rules_only_labels(inputs$labels,checks)$label)),sum(is.na(inputs$labels$label)))
})
